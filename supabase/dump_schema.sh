#!/usr/bin/env bash
# Regenerates supabase/schema.sql from a live database: the public schema, plus what a
# fresh project also needs from other schemas (triggers on auth.users, Storage buckets
# and policies). Structure only, no data.
#
#   SUPABASE_DB_URL='postgresql://postgres.<ref>:<db-password>@<pooler-host>:5432/postgres' ./supabase/dump_schema.sh
#
# Connection string: Supabase dashboard -> Connect -> Session pooler.
# Runs pg_dump 17 in a container (podman or docker), so nothing has to be installed.
set -euo pipefail
: "${SUPABASE_DB_URL:?set SUPABASE_DB_URL (see header)}"
cd "$(dirname "$0")"
RUN=$(command -v podman || command -v docker) || { echo "needs podman or docker" >&2; exit 1; }
pg() { "$RUN" run --rm -i -e PGURL="$SUPABASE_DB_URL" docker.io/library/postgres:17-alpine sh -c "$1"; }

out=schema.sql.tmp
trap 'rm -f "$out"' EXIT
{
  echo "-- Finoteku database schema. Generated by supabase/dump_schema.sh; do not edit by hand."
  echo "-- Fresh project: run this whole file once in the Supabase SQL editor."
  echo
  # newer pg_dump adds \restrict lines; they are psql-only and break the SQL editor
  pg 'pg_dump "$PGURL" --schema-only --schema=public --no-owner --quote-all-identifiers' | sed -E '/^\\(un)?restrict /d'
  echo
  echo "-- ---------------------------------------------------------------------------"
  echo "-- Outside the public schema"
  echo "-- ---------------------------------------------------------------------------"
  pg 'psql "$PGURL" -At -v ON_ERROR_STOP=1' <<'SQL'
SELECT '-- triggers on auth.users';
SELECT format('DROP TRIGGER IF EXISTS %I ON auth.users;', tgname) || E'\n' || pg_get_triggerdef(oid) || ';'
  FROM pg_trigger WHERE tgrelid = 'auth.users'::regclass AND NOT tgisinternal ORDER BY tgname;
SELECT '-- storage buckets';
SELECT format('INSERT INTO storage.buckets (id, name, public) VALUES (%L, %L, %s) ON CONFLICT (id) DO NOTHING;', id, name, public)
  FROM storage.buckets ORDER BY id;
SELECT '-- storage policies';
SELECT format('DROP POLICY IF EXISTS %I ON storage.objects;', policyname) || E'\n' ||
       format('CREATE POLICY %I ON storage.objects AS %s FOR %s TO %s%s%s;', policyname, permissive, cmd,
              array_to_string(roles, ', '),
              coalesce(' USING (' || qual || ')', ''), coalesce(' WITH CHECK (' || with_check || ')', ''))
  FROM pg_policies WHERE schemaname = 'storage' AND tablename = 'objects' ORDER BY policyname;
SQL
} > "$out"
mv "$out" schema.sql
echo "wrote supabase/schema.sql ($(wc -l < schema.sql) lines)"
