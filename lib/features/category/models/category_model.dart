enum CategoryType {
  income,
  expense;

  String get displayName {
    switch (this) {
      case CategoryType.income:
        return 'Income';
      case CategoryType.expense:
        return 'Expense';
    }
  }

  static CategoryType fromString(String value) {
    switch (value.toLowerCase()) {
      case 'income':
        return CategoryType.income;
      case 'expense':
        return CategoryType.expense;
      default:
        throw ArgumentError('Invalid category type: $value');
    }
  }
}

class CategoryModel {
  final String id;
  final String userId;
  final String name;
  final CategoryType type;
  final String? parentId;
  final bool isActive;
  final bool isDeleted;
  final bool needsSync;
  final DateTime? createdAt;
  final DateTime? updatedAt;
  final DateTime? lastSyncAt;

  const CategoryModel({
    required this.id,
    required this.userId,
    required this.name,
    required this.type,
    this.parentId,
    this.isActive = true,
    this.isDeleted = false,
    this.needsSync = false,
    this.createdAt,
    this.updatedAt,
    this.lastSyncAt,
  });

  factory CategoryModel.fromJson(Map<String, dynamic> json) {
    return CategoryModel(
      id: json['id'] ?? '',
      userId: json['userId'] ?? '',
      name: json['name'] ?? '',
      type: CategoryType.fromString(json['type'] ?? 'expense'),
      parentId: json['parentId'],
      isActive: json['isActive'] ?? true,
      isDeleted: json['isDeleted'] ?? false,
      needsSync: json['needsSync'] ?? false,
      createdAt: json['createdAt'] != null 
          ? DateTime.parse(json['createdAt']) 
          : null,
      updatedAt: json['updatedAt'] != null 
          ? DateTime.parse(json['updatedAt']) 
          : null,
      lastSyncAt: json['lastSyncAt'] != null 
          ? DateTime.parse(json['lastSyncAt']) 
          : null,
    );
  }

  Map<String, dynamic> toJson() {
    return {
      'id': id,
      'userId': userId,
      'name': name,
      'type': type.name,
      'parentId': parentId,
      'isActive': isActive,
      'isDeleted': isDeleted,
      'needsSync': needsSync,
      'createdAt': createdAt?.toIso8601String(),
      'updatedAt': updatedAt?.toIso8601String(),
      'lastSyncAt': lastSyncAt?.toIso8601String(),
    };
  }

  /// Create a new category for creation
  factory CategoryModel.create({
    required String userId,
    required String name,
    required CategoryType type,
    String? parentId,
  }) {
    final now = DateTime.now();
    return CategoryModel(
      id: '', // Will be generated by the service
      userId: userId,
      name: name,
      type: type,
      parentId: parentId,
      isActive: true,
      isDeleted: false,
      needsSync: true,
      createdAt: now,
      updatedAt: now,
    );
  }

  /// Create a copy with updated fields
  CategoryModel copyWith({
    String? id,
    String? userId,
    String? name,
    CategoryType? type,
    String? parentId,
    bool? isActive,
    bool? isDeleted,
    bool? needsSync,
    DateTime? createdAt,
    DateTime? updatedAt,
    DateTime? lastSyncAt,
  }) {
    return CategoryModel(
      id: id ?? this.id,
      userId: userId ?? this.userId,
      name: name ?? this.name,
      type: type ?? this.type,
      parentId: parentId ?? this.parentId,
      isActive: isActive ?? this.isActive,
      isDeleted: isDeleted ?? this.isDeleted,
      needsSync: needsSync ?? this.needsSync,
      createdAt: createdAt ?? this.createdAt,
      updatedAt: updatedAt ?? this.updatedAt,
      lastSyncAt: lastSyncAt ?? this.lastSyncAt,
    );
  }

  /// Update category
  CategoryModel update({
    String? name,
    CategoryType? type,
    String? parentId,
    bool? isActive,
  }) {
    return copyWith(
      name: name ?? this.name,
      type: type ?? this.type,
      parentId: parentId ?? this.parentId,
      isActive: isActive ?? this.isActive,
      needsSync: true,
      updatedAt: DateTime.now(),
    );
  }

  /// Mark as deleted (soft delete)
  CategoryModel delete() {
    return copyWith(
      isDeleted: true,
      isActive: false,
      needsSync: true,
      updatedAt: DateTime.now(),
    );
  }

  /// Mark as synced
  CategoryModel markAsSynced() {
    return copyWith(
      needsSync: false,
      lastSyncAt: DateTime.now(),
    );
  }

  /// Convert to database format
  Map<String, dynamic> toDatabaseJson() {
    return {
      'id': id.isEmpty ? null : id,
      'user_id': userId,
      'name': name,
      'type': type.name,
      'parent_id': parentId,
      'is_active': isActive,
      'created_at': createdAt?.toIso8601String(),
      'updated_at': updatedAt?.toIso8601String(),
    };
  }

  /// Create from database format
  factory CategoryModel.fromDatabase(Map<String, dynamic> json) {
    return CategoryModel(
      id: json['id'] ?? '',
      userId: json['user_id'] ?? '',
      name: json['name'] ?? '',
      type: CategoryType.fromString(json['type'] ?? 'expense'),
      parentId: json['parent_id'],
      isActive: json['is_active'] ?? true,
      isDeleted: false,
      needsSync: false,
      createdAt: json['created_at'] != null 
          ? DateTime.parse(json['created_at']) 
          : null,
      updatedAt: json['updated_at'] != null 
          ? DateTime.parse(json['updated_at']) 
          : null,
    );
  }

  /// Check if this is a parent category
  bool get isParent => parentId == null;

  /// Check if this is a child category
  bool get isChild => parentId != null;

  @override
  bool operator ==(Object other) {
    if (identical(this, other)) return true;
    return other is CategoryModel &&
        other.id == id &&
        other.userId == userId &&
        other.name == name &&
        other.type == type &&
        other.parentId == parentId &&
        other.isActive == isActive &&
        other.isDeleted == isDeleted &&
        other.needsSync == needsSync;
  }

  @override
  int get hashCode {
    return Object.hash(
      id,
      userId,
      name,
      type,
      parentId,
      isActive,
      isDeleted,
      needsSync,
    );
  }

  @override
  String toString() {
    return 'CategoryModel(id: $id, name: $name, type: ${type.name}, parent: $parentId)';
  }
}
