class WalletModel {
  final String id;
  final String userId;
  final String name;
  final double balance;
  final String currency;
  final bool isHidden;
  final bool isDeleted;
  final bool needsSync;
  final DateTime? createdAt;
  final DateTime? updatedAt;
  final DateTime? lastSyncAt;

  const WalletModel({
    required this.id,
    required this.userId,
    required this.name,
    required this.balance,
    required this.currency,
    this.isHidden = false,
    this.isDeleted = false,
    this.needsSync = false,
    this.createdAt,
    this.updatedAt,
    this.lastSyncAt,
  });

  factory WalletModel.fromJson(Map<String, dynamic> json) {
    return WalletModel(
      id: json['id'] ?? '',
      userId: json['userId'] ?? '',
      name: json['name'] ?? '',
      balance: (json['balance'] as num?)?.toDouble() ?? 0.0,
      currency: json['currency'] ?? 'IDR',
      isHidden: json['isHidden'] ?? false,
      isDeleted: json['isDeleted'] ?? false,
      needsSync: json['needsSync'] ?? false,
      createdAt: json['createdAt'] != null 
          ? DateTime.parse(json['createdAt']) 
          : null,
      updatedAt: json['updatedAt'] != null 
          ? DateTime.parse(json['updatedAt']) 
          : null,
      lastSyncAt: json['lastSyncAt'] != null 
          ? DateTime.parse(json['lastSyncAt']) 
          : null,
    );
  }

  Map<String, dynamic> toJson() {
    return {
      'id': id,
      'userId': userId,
      'name': name,
      'balance': balance,
      'currency': currency,
      'isHidden': isHidden,
      'isDeleted': isDeleted,
      'needsSync': needsSync,
      'createdAt': createdAt?.toIso8601String(),
      'updatedAt': updatedAt?.toIso8601String(),
      'lastSyncAt': lastSyncAt?.toIso8601String(),
    };
  }

  /// Create a new wallet for creation
  factory WalletModel.create({
    required String userId,
    required String name,
    required double balance,
    required String currency,
  }) {
    final now = DateTime.now();
    return WalletModel(
      id: '', // Will be generated by the service
      userId: userId,
      name: name,
      balance: balance,
      currency: currency,
      isHidden: false,
      isDeleted: false,
      needsSync: true,
      createdAt: now,
      updatedAt: now,
    );
  }

  /// Create a copy with updated fields
  WalletModel copyWith({
    String? id,
    String? userId,
    String? name,
    double? balance,
    String? currency,
    bool? isHidden,
    bool? isDeleted,
    bool? needsSync,
    DateTime? createdAt,
    DateTime? updatedAt,
    DateTime? lastSyncAt,
  }) {
    return WalletModel(
      id: id ?? this.id,
      userId: userId ?? this.userId,
      name: name ?? this.name,
      balance: balance ?? this.balance,
      currency: currency ?? this.currency,
      isHidden: isHidden ?? this.isHidden,
      isDeleted: isDeleted ?? this.isDeleted,
      needsSync: needsSync ?? this.needsSync,
      createdAt: createdAt ?? this.createdAt,
      updatedAt: updatedAt ?? this.updatedAt,
      lastSyncAt: lastSyncAt ?? this.lastSyncAt,
    );
  }

  /// Create a copy with updated fields
  WalletModel update({
    String? name,
    double? balance,
    String? currency,
    bool? isHidden,
  }) {
    return copyWith(
      name: name ?? this.name,
      balance: balance ?? this.balance,
      currency: currency ?? this.currency,
      isHidden: isHidden ?? this.isHidden,
      needsSync: true,
      updatedAt: DateTime.now(),
    );
  }

  /// Mark as deleted (soft delete)
  WalletModel delete() {
    return copyWith(
      isDeleted: true,
      isHidden: true,
      needsSync: true,
      updatedAt: DateTime.now(),
    );
  }

  /// Mark as synced
  WalletModel markAsSynced() {
    return copyWith(
      needsSync: false,
      lastSyncAt: DateTime.now(),
    );
  }

  /// Convert to database format
  Map<String, dynamic> toDatabaseJson() {
    return {
      'id': id.isEmpty ? null : id,
      'user_id': userId,
      'name': name,
      'balance': balance,
      'currency': currency,
      'is_hidden': isHidden,
      'created_at': createdAt?.toIso8601String(),
      'updated_at': updatedAt?.toIso8601String(),
    };
  }

  /// Create from database format
  factory WalletModel.fromDatabase(Map<String, dynamic> json) {
    return WalletModel(
      id: json['id'] ?? '',
      userId: json['user_id'] ?? '',
      name: json['name'] ?? '',
      balance: (json['balance'] as num?)?.toDouble() ?? 0.0,
      currency: json['currency'] ?? 'IDR',
      isHidden: json['is_hidden'] ?? false,
      isDeleted: false,
      needsSync: false,
      createdAt: json['created_at'] != null 
          ? DateTime.parse(json['created_at']) 
          : null,
      updatedAt: json['updated_at'] != null 
          ? DateTime.parse(json['updated_at']) 
          : null,
    );
  }

  @override
  bool operator ==(Object other) {
    if (identical(this, other)) return true;
    return other is WalletModel &&
        other.id == id &&
        other.userId == userId &&
        other.name == name &&
        other.balance == balance &&
        other.currency == currency &&
        other.isHidden == isHidden &&
        other.isDeleted == isDeleted &&
        other.needsSync == needsSync;
  }

  @override
  int get hashCode {
    return Object.hash(
      id,
      userId,
      name,
      balance,
      currency,
      isHidden,
      isDeleted,
      needsSync,
    );
  }

  @override
  String toString() {
    return 'WalletModel(id: $id, name: $name, balance: $balance, currency: $currency)';
  }
}
